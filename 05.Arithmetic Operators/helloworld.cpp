#include <iostream>
#include <vector>



int main() {

    double students = 21;

    std::cout<<students<<std::endl;
    students+=1;
    std::cout<<students<<std::endl;
    students++;
    std::cout<<students<<std::endl;
    students*=4;
    std::cout<<students<<std::endl;
    students--;
    std::cout<<students<<std::endl;
    students-=5;
    std::cout<<students<<std::endl;
    students/=3;
    std::cout<<students<<std::endl;
    


   return 0;

}